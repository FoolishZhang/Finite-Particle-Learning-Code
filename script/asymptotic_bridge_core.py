"""Deterministic eight-label Price bridge kernels and role-split bank inputs.

No module import draws random numbers or writes files. Spins are {-1,+1};
physical c12 is array pair (0,1). A bank is the independent sampling unit.
"""
from __future__ import annotations

import itertools
import os
for _name in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "NUMEXPR_NUM_THREADS"):
    os.environ[_name] = "1"

import numpy as np
from scipy.special import expit, log_expit, logsumexp

N_VALUES = (64, 256, 1024, 4096)
K = 100
YS = np.asarray(list(itertools.product((-1, 1), repeat=3)), dtype=np.int8)
LABEL_ENCODING = "spins_minus1_plus1_lexicographic"
PAIR_ORDER = ((0, 1), (0, 2), (1, 2))
METRIC_NAMES = ["path_gap", "D12", "overlap", "coupling", "direct_gap_truncated"]
RHO_FIXED = .45
RHO_END = .9
ACTIVE_TRUNCATION = 8.
# Prefreeze naming isolation from the earlier, unscored throughput fixture.
# That fixture's actual seed is retained in its own receipt; no scientific
# bank from either family has been generated by this implementation yet.
SEED_FAMILY = 202610080711
BLOCK = 64
TOTAL_BANKS = 131072
BLOCK_COUNT = TOTAL_BANKS // BLOCK
WORKERS = 6
SCHEMA_VERSION = "1.0"


def equicorrelated(active: np.ndarray, rho: float | np.ndarray) -> np.ndarray:
    """Symmetric positive square-root coupling for C(rho), same shape as active."""
    z = np.asarray(active, dtype=np.float64)
    if z.ndim != 3 or z.shape[2] != 3 or not np.isfinite(z).all():
        raise ValueError("active must be finite float64 (B,K,3)")
    rr = np.asarray(rho, dtype=np.float64)
    if rr.ndim == 0:
        rr = np.full(len(z), float(rr))
    if rr.shape != (len(z),) or not np.isfinite(rr).all() or np.any(rr <= -.5) or np.any(rr >= 1):
        raise ValueError("rho must be scalar or (B,) and lie in (-.5,1)")
    diagonal = np.sqrt(1 - rr)[:, None, None]
    common = ((np.sqrt(1 + 2 * rr) - np.sqrt(1 - rr)) / 3)[:, None, None]
    return diagonal * z + common * np.sum(z, axis=2, keepdims=True)


def posterior_gamma(logits: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Stable pi and pi(1-pi), preserving the dominant particle's complement.

    A direct 1-pi loses small complements once dominant pi rounds to 1.
    The dominant complement is therefore the sum of the other probabilities.
    This algorithm is fixed for all manufactured and production calculations.
    """
    a = np.asarray(logits, dtype=np.float64)
    if a.ndim != 2 or not a.shape[1] or not np.isfinite(a).all():
        raise ValueError("logits must be finite (B,K), K>=1")
    maximum = np.argmax(a, axis=1)
    weights = np.exp(a - a[np.arange(len(a)), maximum, None])
    denominator = np.sum(weights, axis=1, keepdims=True)
    pi = weights / denominator
    gamma = pi * (1 - pi)
    others = weights.copy()
    others[np.arange(len(a)), maximum] = 0.
    complement = np.sum(others, axis=1) / denominator[:, 0]
    gamma[np.arange(len(a)), maximum] = pi[np.arange(len(a)), maximum] * complement
    return pi, gamma


def label_price(x: np.ndarray, s: np.ndarray, y: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Per label (pi, gamma, signed residual) at already correlated coordinates."""
    signed = x * y
    logits = s + np.sum(log_expit(signed), axis=2)
    pi, gamma = posterior_gamma(logits)
    residual = y * expit(-signed)
    return pi, gamma, residual


def fixed_price(x: np.ndarray, s: np.ndarray, m_H: float) -> np.ndarray:
    """Eight-label averaged physical D12, overlap and centered coupling (B,3)."""
    out = np.zeros((len(x), 3), dtype=np.float64)
    for y in YS:
        _, gamma, residual = label_price(x, s, y)
        h12 = residual[:, :, 0] * residual[:, :, 1]
        out[:, 0] -= np.sum(gamma * h12, axis=1) / 8
        out[:, 1] += np.sum(gamma, axis=1) / 8
        out[:, 2] += np.sum(gamma * (h12 - m_H), axis=1) / 8
    return out


def path_price_gap(x: np.ndarray, s: np.ndarray) -> np.ndarray:
    """-.9 times sum of three physical Price derivatives at random rho."""
    out = np.zeros(len(x), dtype=np.float64)
    for y in YS:
        _, gamma, r = label_price(x, s, y)
        pairs = r[:, :, 0] * r[:, :, 1] + r[:, :, 0] * r[:, :, 2] + r[:, :, 1] * r[:, :, 2]
        out += RHO_END / 8 * np.sum(gamma * pairs, axis=1)
    return out


def direct_gap(z: np.ndarray, xb: np.ndarray, s: np.ndarray) -> np.ndarray:
    """All eight labels: loss(I)-loss(C(.9)); common nuisance normalization cancels."""
    out = np.zeros(len(z), dtype=np.float64)
    centered = s - np.max(s, axis=1, keepdims=True)
    for y in YS:
        li = centered + np.sum(log_expit(z * y), axis=2)
        lb = centered + np.sum(log_expit(xb * y), axis=2)
        out += (logsumexp(lb, axis=1) - logsumexp(li, axis=1)) / 8
    return out


def score_block(z: np.ndarray, s_prefix: np.ndarray, u: np.ndarray, m_H: float) -> tuple[np.ndarray, np.ndarray]:
    """Return (scores[B,4,5], clipmask[B]); primary path metric is never clipped.

    s_prefix[B,4,K] uses N_VALUES order. The four n arms, labels and three
    coordinates are correlated readings from one bank, not independent draws.
    u contains rho, already scaled to [0,.9]. m_H is the frozen numerical
    reference m_H45, not an estimate from these banks.
    """
    z = np.asarray(z, dtype=np.float64)
    s = np.asarray(s_prefix, dtype=np.float64)
    u = np.asarray(u, dtype=np.float64)
    if z.ndim != 3 or z.shape[2] != 3 or min(z.shape[:2]) < 1:
        raise ValueError("z must have shape (B,K,3)")
    if s.shape != (len(z), len(N_VALUES), z.shape[1]) or u.shape != (len(z),):
        raise ValueError("s_prefix must be (B,4,K), u must be (B,)")
    if not all(np.isfinite(a).all() for a in (z, s, u)) or np.any(u < 0) or np.any(u > RHO_END):
        raise ValueError("inputs must be finite and u in [0,.9]")
    m_H = float(m_H)
    if not np.isfinite(m_H) or abs(m_H) > 1:
        raise ValueError("m_H must be a finite reference in [-1,1]")
    xfixed, xpath, xb = (equicorrelated(z, rho) for rho in (RHO_FIXED, u, RHO_END))
    result = np.empty((len(z), len(N_VALUES), len(METRIC_NAMES)), dtype=np.float64)
    clipmask = np.max(np.abs(z), axis=(1, 2)) > ACTIVE_TRUNCATION
    for ni in range(len(N_VALUES)):
        weights = s[:, ni, :]
        result[:, ni, 0] = path_price_gap(xpath, weights)
        result[:, ni, 1:4] = fixed_price(xfixed, weights, m_H)
        gap = direct_gap(z, xb, weights)
        gap[clipmask] = 0.
        result[:, ni, 4] = gap
    if not np.isfinite(result).all():
        raise FloatingPointError("nonfinite bridge score")
    return result, clipmask


def generate_block(block_id: int, *, seed_family: int = SEED_FAMILY, banks: int = BLOCK,
                   particles: int = K) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Role-split PCG64DXSM inputs; nuisance log_expit uses the Gaussian buffer in-place.

    The four segments 64/192/768/3072 are summed before cumulative addition;
    there is no full nuisance cumsum copy. This function is also available to
    independent audit. Call it for scientific seeds only after source freeze.
    """
    if isinstance(block_id, bool) or not isinstance(block_id, (int, np.integer)) or block_id < 0:
        raise ValueError("block_id must be a nonnegative integer")
    if banks < 1 or particles < 1:
        raise ValueError("positive banks and particles required")
    def rng(role: int) -> np.random.Generator:
        return np.random.Generator(np.random.PCG64DXSM(np.random.SeedSequence([seed_family, int(block_id), role])))
    z = rng(0).standard_normal((banks, particles, 3))
    noise = rng(1).standard_normal((banks, particles, N_VALUES[-1]))
    log_expit(noise, out=noise)
    prefixes = np.empty((banks, len(N_VALUES), particles), dtype=np.float64)
    cumulative = np.zeros((banks, particles), dtype=np.float64)
    first = 0
    for ni, last in enumerate(N_VALUES):
        cumulative += np.sum(noise[:, :, first:last], axis=2)
        prefixes[:, ni, :] = cumulative
        first = last
    u = RHO_END * rng(2).random(banks)
    return z, prefixes, u


def production_config() -> dict:
    return dict(banks=TOTAL_BANKS, particles=K, n_values=list(N_VALUES), block=BLOCK,
                block_count=BLOCK_COUNT, workers=WORKERS, seed_family=SEED_FAMILY,
                roles={"active": 0, "nuisance": 1, "uniform_rho": 2}, rho_fixed=RHO_FIXED,
                rho_end=RHO_END, metric_names=METRIC_NAMES, label_encoding=LABEL_ENCODING,
                dtype="float64", nuisance_prefix_method="inplace_log_expit_segment_sum_then_add",
                gamma_method="dominant_complement_from_other_weights", cpu_threads_per_worker=1)
